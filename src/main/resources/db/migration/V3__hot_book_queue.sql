-- 书目级续借暂停（热门书需求调控：等待人数过多时馆员可暂停该书续借，加快复本回转）
ALTER TABLE bibs ADD COLUMN renew_suspended BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE bibs ADD COLUMN renew_suspend_reason VARCHAR(512);

-- 馆藏流转记录：新增采购到馆、自动分配、人工调整（调整原因强制留痕）
CREATE TABLE item_movements (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id          BIGINT NOT NULL REFERENCES items(id),
    -- ACQUISITION 采购到馆 / AUTO_ASSIGN 系统按队列自动分配 / MANUAL_ADJUST 馆员人工调整分配
    type             VARCHAR(24) NOT NULL,
    from_library_id  BIGINT REFERENCES libraries(id),
    to_library_id    BIGINT REFERENCES libraries(id),
    hold_id          BIGINT REFERENCES holds(id),
    staff            VARCHAR(64),
    reason           VARCHAR(512),
    detail           VARCHAR(1024),
    created_at       TIMESTAMP NOT NULL
);
CREATE INDEX idx_movements_item ON item_movements(item_id, created_at);

