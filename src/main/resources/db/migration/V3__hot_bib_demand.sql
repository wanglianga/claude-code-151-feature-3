-- 热门书预约队列调整：采购建议、新增复本均衡分配、暂停续借、馆藏流转留痕
-- 通用 SQL 子集，可同时在 PostgreSQL 与 H2(PostgreSQL 模式) 上由 Flyway 执行
-- 另：items.status 新增取值 RECEIVED（新采购到馆待馆员确认分配，不参与在架可借检索）

-- 新增复本采购批次（馆员登记到馆新复本，按需求建议确定采购数量）
CREATE TABLE item_acquisitions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bib_id          BIGINT NOT NULL REFERENCES bibs(id),
    copy_count      INTEGER NOT NULL,
    -- RECEIVED 新复本已到馆待分配 / ALLOCATED 已全部分配完成 / CANCELLED 批次取消
    status          VARCHAR(16) NOT NULL,
    staff           VARCHAR(64),
    note            VARCHAR(512),
    created_at      TIMESTAMP NOT NULL,
    allocated_at    TIMESTAMP
);
CREATE INDEX idx_acq_bib ON item_acquisitions(bib_id, status);

-- 采购批次内每一册新复本及其分配去向（系统给建议，馆员可改派，留痕）
CREATE TABLE copy_allocations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acquisition_id    BIGINT NOT NULL REFERENCES item_acquisitions(id),
    item_id           BIGINT NOT NULL REFERENCES items(id),
    hold_id           BIGINT REFERENCES holds(id),
    target_library_id BIGINT NOT NULL REFERENCES libraries(id),
    -- SUGGESTED 系统建议待馆员确认 / CONFIRMED 馆员确认并执行 /
    -- MANUAL 馆员手动改派后确认 / SKIPPED 暂不分配（复本在目标馆上架可借）
    status            VARCHAR(16) NOT NULL,
    -- SYSTEM 系统自动 / STAFF 馆员手动改派
    decided_by        VARCHAR(16) NOT NULL,
    staff             VARCHAR(64),
    -- LOCAL 目标馆即为读者取书馆，到馆即上架 / TRANSFER 需先配送到取书馆
    fulfill_mode      VARCHAR(16) NOT NULL,
    eta_hours         BIGINT NOT NULL DEFAULT 0,
    pickup_window_end TIMESTAMP,
    reason            VARCHAR(512),
    created_at        TIMESTAMP NOT NULL,
    decided_at        TIMESTAMP
);
CREATE INDEX idx_alloc_acq ON copy_allocations(acquisition_id);
CREATE INDEX idx_alloc_hold ON copy_allocations(hold_id);
CREATE INDEX idx_alloc_status ON copy_allocations(status);

-- 热门书暂停续借冻结（按书目生效/解除；队列消化后可解除）
CREATE TABLE hold_renewal_freezes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bib_id      BIGINT NOT NULL REFERENCES bibs(id),
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    staff       VARCHAR(64) NOT NULL,
    reason      VARCHAR(512) NOT NULL,
    created_at  TIMESTAMP NOT NULL,
    released_at TIMESTAMP,
    release_staff   VARCHAR(64),
    release_reason  VARCHAR(512)
);
CREATE INDEX idx_freeze_bib_active ON hold_renewal_freezes(bib_id, active);

-- 馆藏流转记录：新增复本到馆、系统/馆员分配、改派、暂停续借等全部可审计
CREATE TABLE collection_flow_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bib_id      BIGINT REFERENCES bibs(id),
    item_id     BIGINT REFERENCES items(id),
    hold_id     BIGINT REFERENCES holds(id),
    -- ACQUISITION 新增采购到馆 / ALLOCATION_SYSTEM 系统分配建议 /
    -- ALLOCATION_MANUAL 馆员手动改派 / ALLOCATION_EXECUTE 建议确认执行 /
    -- RENEW_FREEZE 暂停续借 / RENEW_RELEASE 解除暂停续借 / ACQUISITION_CANCEL 采购取消
    action      VARCHAR(32) NOT NULL,
    detail      VARCHAR(1024) NOT NULL,
    staff       VARCHAR(64),
    created_at  TIMESTAMP NOT NULL
);
CREATE INDEX idx_flow_bib ON collection_flow_logs(bib_id, created_at);
CREATE INDEX idx_flow_item ON collection_flow_logs(item_id);

